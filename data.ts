import { Teacher, Student } from './types';

const parseStudents = (raw: string): Student[] => {
  return raw.trim().split('\n').map(line => {
    // Using regex to handle both tabs and spaces
    const match = line.trim().match(/^(\d+)[\s\t]+(.+)$/);
    if (!match) return null;
    
    const id = parseInt(match[1]);
    const name = match[2].trim();
    const gender = name.startsWith('ด.ช.') ? 'male' : 'female';
    return { id, name, gender: gender as 'male' | 'female' };
  }).filter((s): s is Student => s !== null);
};

